def add(a, b):
    """Повертає суму двох чисел."""
    return a + b


def subtract(a, b):
    """Повертає різницю двох чисел."""
    return a - b


def multiply(a, b):
    """Повертає добуток двох чисел."""
    return a * b
def divide(a, b):
    """Повертає результат ділення двох чисел."""
    return a / b
